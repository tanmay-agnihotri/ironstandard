import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { MEAL_TYPES, findMeal, dayKeyForDate, fmtDate } from './data.js';

function addDays(iso, n) {
  const d = new Date(iso + 'T00:00:00');
  d.setDate(d.getDate() + n);
  return d;
}

function brandHeader(doc, subtitle) {
  const pageWidth = doc.internal.pageSize.getWidth();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(20, 20, 20);
  doc.text('IRON STANDARD', 40, 50);
  doc.setFontSize(12);
  doc.setTextColor(224, 34, 44);
  doc.text(subtitle, 40, 68);
  doc.setDrawColor(224, 34, 44);
  doc.setLineWidth(1.5);
  doc.line(40, 78, pageWidth - 40, 78);
  return pageWidth;
}

function footer(doc) {
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(9);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by Iron Standard — Powerlifting Self-Coach', 40, doc.internal.pageSize.getHeight() - 30);
}

// ---------- Training Plan PDF ----------

export function generatePlanPDF(program, startDate) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = brandHeader(doc, 'Training Plan');
  let y = 100;

  program.forEach((day, i) => {
    const date = startDate ? addDays(startDate, i) : null;
    const dateLabel = date ? date.toLocaleDateString(undefined, { weekday: 'long', month: 'short', day: 'numeric' }) : '';

    if (y > 700) { doc.addPage(); y = 50; }

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(20, 20, 20);
    doc.text(`Day ${i + 1}: ${day.focus}`, 40, y);

    if (dateLabel) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(120, 120, 120);
      doc.text(dateLabel, pageWidth - 40, y, { align: 'right' });
    }

    autoTable(doc, {
      startY: y + 10,
      margin: { left: 40, right: 40 },
      head: [['Exercise', 'Sets', 'Note']],
      body: day.exercises.map((e) => [e.name, e.sets, e.note || '']),
      styles: { fontSize: 10, cellPadding: 6 },
      headStyles: { fillColor: [10, 10, 11], textColor: [245, 244, 240] },
      alternateRowStyles: { fillColor: [246, 246, 246] },
      theme: 'grid',
    });

    y = doc.lastAutoTable.finalY + 28;
  });

  footer(doc);
  return doc;
}

// ---------- Progress / Coach Report PDF ----------

export function buildDailyReports(dateRange, trainlogs, dietLog, mealPlan, program) {
  return dateRange.map((date) => {
    const workout = trainlogs.find((t) => t.date === date) || null;
    const dayKey = dayKeyForDate(date);
    const planned = mealPlan[dayKey] || {};
    const plannedMeals = MEAL_TYPES
      .map((mt) => (planned[mt.id] ? findMeal(mt.id, planned[mt.id]) : null))
      .filter(Boolean);
    const dietEntry = dietLog.find((d) => d.date === date) || null;

    let assignedExercises = [];
    if (workout && workout.dayRef != null && workout.dayRef !== 'custom' && program[parseInt(workout.dayRef)]) {
      assignedExercises = program[parseInt(workout.dayRef)].exercises;
    }

    return { date, workout, plannedMeals, dietEntry, assignedExercises };
  });
}

export function generateProgressReportPDF({ dateRange, trainlogs, dietLog, mealPlan, program, profile }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = brandHeader(doc, 'Progress Report');

  const reports = buildDailyReports(dateRange, trainlogs, dietLog, mealPlan, program);
  const workoutsDone = reports.filter((r) => r.workout?.completion === 'full').length;
  const workoutsLogged = reports.filter((r) => r.workout).length;
  const dietFollowed = reports.filter((r) => r.dietEntry?.followed === 'full').length;
  const dietLogged = reports.filter((r) => r.dietEntry).length;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  doc.text(`${fmtDate(dateRange[0])} to ${fmtDate(dateRange[dateRange.length - 1])} (${dateRange.length} days)`, 40, 92);
  if (profile) doc.text(`Lifter: ${profile.currentWeight}kg, working toward ${profile.goalWeight}kg`, 40, 106);

  let y = 130;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(20, 20, 20);
  doc.text('Summary', 40, y);
  y += 8;
  autoTable(doc, {
    startY: y,
    margin: { left: 40, right: 40 },
    head: [['Workouts Logged', 'Workouts Completed', 'Diet Logged', 'Diet Followed']],
    body: [[`${workoutsLogged}/${dateRange.length}`, `${workoutsDone}/${dateRange.length}`, `${dietLogged}/${dateRange.length}`, `${dietFollowed}/${dateRange.length}`]],
    styles: { fontSize: 10, cellPadding: 7, halign: 'center' },
    headStyles: { fillColor: [10, 10, 11], textColor: [245, 244, 240] },
    theme: 'grid',
  });
  y = doc.lastAutoTable.finalY + 24;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Day by Day', 40, y);
  y += 8;

  autoTable(doc, {
    startY: y,
    margin: { left: 40, right: 40 },
    head: [['Date', 'Workout Assigned', 'Completion', 'Meals Assigned', 'Diet Followed']],
    body: reports.map((r) => [
      fmtDate(r.date),
      r.workout ? r.workout.dayLabel : '— not logged —',
      r.workout ? r.workout.completion : '—',
      r.plannedMeals.length ? r.plannedMeals.map((m) => m.name).join(', ') : '— none planned —',
      r.dietEntry ? r.dietEntry.followed : 'not logged',
    ]),
    styles: { fontSize: 9, cellPadding: 6 },
    headStyles: { fillColor: [10, 10, 11], textColor: [245, 244, 240] },
    alternateRowStyles: { fillColor: [246, 246, 246] },
    theme: 'grid',
    columnStyles: { 3: { cellWidth: 160 } },
  });
  y = doc.lastAutoTable.finalY + 24;

  // Per-exercise detail for days that actually had a logged workout
  const withWorkouts = reports.filter((r) => r.workout && r.assignedExercises.length);
  if (withWorkouts.length) {
    if (y > 650) { doc.addPage(); y = 50; }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text('Exercise Detail', 40, y);
    y += 8;

    withWorkouts.forEach((r) => {
      if (y > 680) { doc.addPage(); y = 50; }
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(224, 34, 44);
      doc.text(`${fmtDate(r.date)} — ${r.workout.dayLabel}`, 40, y);
      y += 6;

      const rows = r.assignedExercises.map((assigned) => {
        const done = r.workout.exercises.find((e) => e.name === assigned.name);
        const doneStr = done && (done.weight || done.sets || done.reps)
          ? `${done.weight || '—'}kg × ${done.sets || '—'} sets × ${done.reps || '—'} reps (RPE ${done.rpe || '—'})`
          : 'not logged';
        return [assigned.name, assigned.sets, doneStr];
      });

      autoTable(doc, {
        startY: y + 4,
        margin: { left: 40, right: 40 },
        head: [['Exercise', 'Assigned', 'Actually Done']],
        body: rows,
        styles: { fontSize: 9, cellPadding: 5 },
        headStyles: { fillColor: [40, 40, 42], textColor: [245, 244, 240] },
        theme: 'grid',
      });
      y = doc.lastAutoTable.finalY + 18;
    });
  }

  footer(doc);
  return doc;
}

// ---------- Shared download / share actions ----------

export function downloadPDF(doc, fileName) {
  doc.save(fileName);
}

export async function sharePDF(doc, fileName, title) {
  const blob = doc.output('blob');
  const file = new File([blob], fileName, { type: 'application/pdf' });

  if (navigator.canShare && navigator.canShare({ files: [file] })) {
    try {
      await navigator.share({ files: [file], title });
      return 'shared';
    } catch (err) {
      if (err.name === 'AbortError') return 'cancelled';
    }
  }
  doc.save(fileName);
  return 'downloaded';
}
